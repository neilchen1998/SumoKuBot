#ifndef APPS_CLI_ARGUMENTS_HPP
#define APPS_CLI_ARGUMENTS_HPP

#include <array>                     // std::array
#include <cstddef>                   // std::size_t
#include <cstdint>                   // std::uint8_t
#include <magic_enum/magic_enum.hpp> // magic_enum::enum_names
#include <string_view>               // std::string_view
#include <utility>                   // std::pair, std::index_sequence

/// @brief The solver type
enum class SolverType : std::uint8_t // packs this enum inside a single byte type
{
    SumokuSolver,
    SumokuMRV,
    SumokuOrdering
};

/// @brief Creates a compile-time mapping between SolverType enum names and values.
/// @tparam I Compile-time indices generated by std::index_sequence.
/// @param[in] std::index_sequence<I...> Sequence of compile-time indices.
/// @return constexpr std::array containing pairs of enum names and values.
template <typename Enum, std::size_t... I>
constexpr auto CompileEnumMap(std::index_sequence<I...>)
{
    constexpr auto values = magic_enum::enum_values<Enum>();
    constexpr auto names = magic_enum::enum_names<Enum>();

    return std::array {std::pair<std::string_view, Enum> {names[I], values[I]}...};
}

/// @brief A map for all the solver types
constexpr auto solverMap = CompileEnumMap<SolverType>(std::make_index_sequence<magic_enum::enum_count<SolverType>()> {});

/// @brief Generates a comma-separated list of available solver names enclosed in braces during compile time.
/// @return A null-terminated character array containing the formatted solver options.
consteval auto GetSolverOptionsText()
{
    constexpr auto solverNames = magic_enum::enum_names<SolverType>();

    constexpr std::size_t maxSize = 48; // adjust this if needed
    std::array<char, maxSize> buffer {};
    std::size_t pos = 0;

    buffer[pos++] = '{';

    for (bool first = true; const auto name : solverNames)
    {
        // Append the comma seperator when there is more than one solver
        if (!first)
        {
            buffer[pos++] = ',';
            buffer[pos++] = ' ';
        }

        // Grab each character from the string_view and append to the buffer
        for (char c : name)
        {
            buffer[pos++] = c;
        }

        first = false;
    }

    buffer[pos++] = '}';
    buffer[pos] = '\0';

    return buffer;
}

/// @brief Overloads the stream insertion operator to convert Solvers enum value to string
/// @param os The output stream
/// @param s The solver type enum value
/// @return A reference to the output stream
std::ostream& operator<<(std::ostream& os, const SolverType& s);

#endif // APPS_CLI_ARGUMENTS_HPP
